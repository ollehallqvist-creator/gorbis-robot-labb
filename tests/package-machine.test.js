const fs=require("node:fs");
const path=require("node:path");
const assert=require("node:assert/strict");
const html=fs.readFileSync(path.join(__dirname,"..","index.html"),"utf8");
const renderer=fs.readFileSync(path.join(__dirname,"..","three-renderer.js"),"utf8");
const dispenseStart=html.indexOf("function dispensePart(){");
const openStart=html.indexOf("function openDispensedPackage(){");
const dragStart=html.indexOf("let dragPointer=null");
assert.ok(dispenseStart>=0&&openStart>dispenseStart&&dragStart>openStart,"machine should have separate dispense and open-package functions");
const dispense=html.slice(dispenseStart,openStart);
const open=html.slice(openStart,dragStart);
assert.ok(!dispense.includes("openedParts.push"),"dispensing a package must not unlock the part yet");
assert.ok(open.includes("openedParts.push(id)"),"clicking the package should unlock its part");
assert.ok(open.includes("packageOpeningPart=id;state.packageOpenedAt=performance.now()"),"opening a package should trigger the opened-part animation");
assert.ok(html.includes('hit3D==="package"'),"the game should recognize a click on the 3D package");
assert.ok(html.includes("if(state.packageOpeningPart!==null&&performance.now()-state.packageOpenedAt<900)"),"Canvas fallback should show the part popping out of the package");
assert.ok(renderer.includes("targets.push(this.refs.packagePart)"),"the 3D raycaster should include the visible package");
assert.ok(renderer.includes("this.refs.packagePart.visible=dispensing;"),"the package should stay visible until the player opens it");
assert.ok(renderer.includes("this.refs.openedPart.visible=opening"),"the opened 3D part should pop out briefly after the second click");
console.log("PASS: package persists until clicked, then unlocks and animates the actual part.");
